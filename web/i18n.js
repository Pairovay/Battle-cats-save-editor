/** Current interface language ("en" or "es"). */
function LANG() {
  const lang = (typeof S !== "undefined" && S.home && S.home.language) || "en";
  return STRINGS[lang] ? lang : "en";
}

const _numberFormats = {};
function numberFormat() {
  const lang = LANG();
  if (!_numberFormats[lang]) _numberFormats[lang] = new Intl.NumberFormat(lang === "es" ? "es-ES" : "en-US");
  return _numberFormats[lang];
}

/** Translates a key, replacing {name} placeholders with the given values. */
function t(key, vars) {
  const text = (STRINGS[LANG()] && STRINGS[LANG()][key]) ?? STRINGS.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : m));
}
